func eastAsianWidth(r rune) eastAsianWidthCategory {
	for _, rg := range eastAsianWidthRanges {
		if rg.lo <= r && r <= rg.hi {
			return rg.cat
		}
	}
	return catNarrowOrNeutral
}

// IsSafeTerminalGlyph reports whether r is guaranteed to render in exactly
// one terminal cell — East Asian Width Narrow or Neutral, never Wide,
// Fullwidth or Ambiguous. This is the SAME table the renderer uses (Phase
// 4); a glyph picked without running it through this function is exactly
// how a row's columns end up misaligned on one terminal and not another.
func IsSafeTerminalGlyph(r rune) bool {
	return eastAsianWidth(r) == catNarrowOrNeutral
}

// IsASCIIGlyph reports whether b is a plain printable ASCII character
// (U+0020..U+007E) — the range every fallback glyph must live in.
func IsASCIIGlyph(b byte) bool {
	return b >= 0x20 && b <= 0x7E
}
